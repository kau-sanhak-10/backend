-- V4: 제조사 공식 매뉴얼 오류코드 (AI-14)
--   사장님 문의 상세에 오류코드의 공식 설명과 출처를 보여 주려고, 제조사 공식 자료실에서 받은 매뉴얼의
--   '에러코드별 자가 조치' 표를 옮겨 둠 - 매뉴얼에 적힌 오류 이름·설명·쪽 번호이지 진단이 아님
--   확인된 제조사·모델·오류코드가 셋 다 맞을 때만 보여 줌 - 같은 제조사라도 모델마다 오류코드가 달라서
--   (예: E492·E740은 거꾸로 ECO 콘덴싱에만 있음) 매뉴얼별로 모델·오류코드를 나눠 둠
--   V1 error_code 표는 제조사·코드로 한 줄이라 모델·문서 버전·쪽을 담지 못해 따로 둠 (error_code는 그대로)
--
-- 처음 넣는 자료: 귀뚜라미 가스보일러 매뉴얼 5개 (2026-11-16 krb.co.kr 자료실에서 받음)
--   설명(description)은 매뉴얼의 '자가 조치 방법' 칸에서 그 코드가 무엇인지 적은 문장만 그대로 옮김
--   (전원 재가동·밸브 확인 같은 조치 단계는 옮기지 않음, 그런 문장이 없는 코드는 NULL)
-- =====================================================================

-- 매뉴얼 한 권
CREATE TABLE official_manual (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer     VARCHAR(50)  NOT NULL, -- 접수 항목 manufacturer 값과 같은 이름, 띄어쓰기 없이 (예: 귀뚜라미)
    product_name     VARCHAR(100) NOT NULL, -- 자료실에 올라온 제품 이름 (예: 거꾸로 ECO 콘덴싱 L20 가스보일러)
    document_name    VARCHAR(100) NOT NULL, -- 표지의 문서 이름 (예: 사용·설치 설명서(품질보증서 재중))
    document_version VARCHAR(50)  NOT NULL, -- 뒤표지 아래 문서 코드 (예: S 260911)
    source_url       VARCHAR(500) NOT NULL, -- 제조사 공식 자료실 - 제품 이름으로 찾음
    file_url         VARCHAR(500) NOT NULL, -- 자료실의 내려받기 주소 (자료실을 거치지 않으면 제조사 사이트가 막을 수 있음)
    checked_on       DATE         NOT NULL, -- 내려받아 옮겨 적은 날
    CONSTRAINT uq_official_manual_id_manufacturer UNIQUE (id, manufacturer), -- 같은 제조사 복합 FK 대상
    CONSTRAINT uq_official_manual_document UNIQUE (manufacturer, product_name, document_version)
);

-- 매뉴얼이 다루는 모델 - 한 제조사 안에서 한 모델은 매뉴얼 하나
-- model_key: 대소문자·띄어쓰기·하이픈·괄호·점·슬래시·밑줄·가운뎃점을 뺀 비교용 값
--   (OfficialErrorCodeLookup.modelKey와 같은 규칙, 모든 행이 맞는지 테스트로 확인)
CREATE TABLE official_manual_model (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manual_id    BIGINT       NOT NULL,
    manufacturer VARCHAR(50)  NOT NULL,
    model_name   VARCHAR(100) NOT NULL, -- 예: 거꾸로 ECO 콘덴싱 L20-15HFN
    model_key    VARCHAR(100) NOT NULL, -- 예: 거꾸로ECO콘덴싱L2015HFN
    CONSTRAINT fk_official_manual_model_manual FOREIGN KEY (manual_id, manufacturer)
        REFERENCES official_manual (id, manufacturer),
    CONSTRAINT uq_official_manual_model_key UNIQUE (manufacturer, model_key)
);

-- 매뉴얼의 오류코드 한 줄
CREATE TABLE official_manual_error_code (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manual_id   BIGINT       NOT NULL,
    code        VARCHAR(20)  NOT NULL, -- 매뉴얼에 적힌 그대로 (예: E001)
    title       VARCHAR(100) NOT NULL, -- '이상 발생 내용' 칸 (예: 점화에러)
    description VARCHAR(500),          -- 그 코드가 무엇인지 적은 매뉴얼 문장 그대로, 없으면 NULL
    page        INT          NOT NULL, -- 매뉴얼에 인쇄된 쪽 번호
    CONSTRAINT fk_official_manual_error_code_manual FOREIGN KEY (manual_id) REFERENCES official_manual (id),
    CONSTRAINT uq_official_manual_error_code UNIQUE (manual_id, code),
    CONSTRAINT ck_official_manual_error_code_page CHECK (page > 0)
);


