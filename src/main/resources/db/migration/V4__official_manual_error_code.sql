     names (product_name, model_name) AS (
         SELECT s.product_name, s.series_name || '-' || m.model_code
         FROM series s
                  JOIN models m ON m.product_name = s.product_name
         UNION ALL
         SELECT product_name, series_name
         FROM series
         WHERE alone
     )
