-- =====================================================================
-- V2__auth_ai_reservation_contract.sql : API 명세 DS-04 v0.3 7.1의 1~9번 + 작업별 자동 예약 허용 (BE-22)
--
-- - 1. inquiry.ai_input_seq : AI 입력 순번, @Version(version)과 따로 오름 (1.7·6.1)
-- - 2. auth_token : 사장님·운영자·문의·고객 토큰 저장소, 원문 대신 SHA-256 해시 (1.5)
-- - 3. inquiry.token_hash·expires_at 삭제 : 문의 토큰은 auth_token으로, 기기마다 따로 발급
-- - 4. reservation.idempotency_hash : 같은 요청 키로 다른 요청이 오면 구분하는 지문 (1.6)
-- - 5. ai_decision : 입력 순번·요청 ID, INVALID_OUTPUT·STALE 상태, 실패 기록은 action 없이 (6.3·6.4)
-- - 6. reservation_change : 제안 만료(EXPIRED)·종료(CLOSED), 취소는 변경 요청 없이 즉시 처리 (2.4·5.3·5.4)
-- - 7. notification : SKIPPED, 예약 사건별 알림 종류 (5.10)
-- - 8. phone_verification : 인증 대상 문의·업체, 요청 IP (5.1 누적 발송 제한)
-- - 9. inquiry_field.message_id : 고객 설명의 근거 메시지 (6.3)
-- - 10. owner_work_type.auto_booking_allowed : 제공 여부(is_active)와 따로 두는 작업별 자동 예약 허용
--
-- 기존 V1 데이터는 칸 삭제·CHECK 교체 전에 먼저 옮기거나 무효화함 (3·4·6·10번)
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. AI 입력 순번
--    AI 판단에 영향을 주는 입력이 들어올 때만 UPDATE 쿼리로 +1 (Entity 수정 아님 → version 그대로)
-- ---------------------------------------------------------------------
ALTER TABLE inquiry
    ADD COLUMN ai_input_seq BIGINT NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_inquiry_ai_input_seq CHECK (ai_input_seq >= 0);


-- ---------------------------------------------------------------------
-- 2. 토큰 저장소
--    토큰 종류마다 쓰는 대상 칸이 정해져 있고, 다른 대상 칸은 비워 둠 (ck_auth_token_subject)
-- ---------------------------------------------------------------------
CREATE TABLE auth_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash     VARCHAR(64) NOT NULL,  -- SHA-256, 원문 저장 금지
    token_type     VARCHAR(20) NOT NULL,  -- OWNER / ADMIN / INQUIRY / CUSTOMER
    owner_id       BIGINT,                -- OWNER: 그 사장님 업체 / CUSTOMER: 조회 범위 업체
    admin_id       BIGINT,                -- ADMIN
    inquiry_id     BIGINT,                -- INQUIRY: 그 문의
    customer_phone VARCHAR(20),           -- CUSTOMER: 인증한 번호
    scope          VARCHAR(30),           -- CUSTOMER: RESERVATION_LOOKUP / INQUIRY_ACCESS
    expires_at     TIMESTAMPTZ NOT NULL,
    revoked_at     TIMESTAMPTZ,           -- 값이 있으면 철회된 토큰
    last_used_at   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_auth_token_owner FOREIGN KEY (owner_id) REFERENCES owner (id),
    CONSTRAINT fk_auth_token_admin FOREIGN KEY (admin_id) REFERENCES admin (id),
    CONSTRAINT fk_auth_token_inquiry FOREIGN KEY (inquiry_id) REFERENCES inquiry (id),
    CONSTRAINT uq_auth_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_auth_token_type CHECK (token_type IN ('OWNER', 'ADMIN', 'INQUIRY', 'CUSTOMER')),
    CONSTRAINT ck_auth_token_subject CHECK (
           (token_type = 'OWNER'    AND owner_id IS NOT NULL AND admin_id IS NULL AND inquiry_id IS NULL AND customer_phone IS NULL AND scope IS NULL)
        OR (token_type = 'ADMIN'    AND admin_id IS NOT NULL AND owner_id IS NULL AND inquiry_id IS NULL AND customer_phone IS NULL AND scope IS NULL)
        OR (token_type = 'INQUIRY'  AND inquiry_id IS NOT NULL AND admin_id IS NULL AND customer_phone IS NULL AND scope IS NULL)
        OR (token_type = 'CUSTOMER' AND owner_id IS NOT NULL AND customer_phone IS NOT NULL AND admin_id IS NULL AND inquiry_id IS NULL
            AND scope IS NOT NULL AND scope IN ('RESERVATION_LOOKUP', 'INQUIRY_ACCESS'))),
    CONSTRAINT ck_auth_token_expiry CHECK (expires_at > created_at)
);

-- 로그인 번호 변경·이용 제한 때 그 업체 토큰 일괄 철회
CREATE INDEX ix_auth_token_owner_active ON auth_token (owner_id) WHERE revoked_at IS NULL;
-- 문의 종료·삭제 때 그 문의 토큰 일괄 철회
CREATE INDEX ix_auth_token_inquiry ON auth_token (inquiry_id);


-- ---------------------------------------------------------------------
-- 3. 문의 토큰을 auth_token으로 옮김
--    아직 쓸 수 있는 토큰(만료 전, 삭제·종료 안 된 문의)만 옮기고 나머지는 칸과 함께 버림
--    문의 토큰은 최대 24시간이라 옮기는 토큰도 지금부터 24시간을 넘지 않게 줄임
-- ---------------------------------------------------------------------
INSERT INTO auth_token (token_hash, token_type, inquiry_id, expires_at)
SELECT token_hash, 'INQUIRY', id, LEAST(expires_at, CURRENT_TIMESTAMP + INTERVAL '24 hours')
FROM inquiry
WHERE expires_at > CURRENT_TIMESTAMP
  AND deleted_at IS NULL
  AND status <> 'CLOSED';

ALTER TABLE inquiry
    DROP CONSTRAINT uq_inquiry_token_hash,
    DROP COLUMN token_hash,
    DROP COLUMN expires_at;


-- ---------------------------------------------------------------------
-- 4. 요청 지문 = SHA-256(요청 경로 + 요청한 주체 + 정규화한 본문)
--    요청 키와 지문은 같이 있거나 같이 없음
--    V1 요청 키는 지문을 다시 만들 수 없어 무효화 (같은 문의 중복 예약은 uq_reservation_active_inquiry가 계속 막음)
-- ---------------------------------------------------------------------
UPDATE reservation SET idempotency_key = NULL WHERE idempotency_key IS NOT NULL;

ALTER TABLE reservation
    ADD COLUMN idempotency_hash VARCHAR(64),
    ADD CONSTRAINT ck_reservation_idempotency_pair CHECK ((idempotency_key IS NULL) = (idempotency_hash IS NULL));


-- ---------------------------------------------------------------------
-- 5. AI 판단 기록
--    input_version = 요청 때의 inquiry.ai_input_seq, 결과가 올 때 더 올랐으면 STALE로 기록만 함
--    실패·형식 오류·오래된 결과는 할 일(action)이 없을 수 있음, SUCCESS만 필수
-- ---------------------------------------------------------------------
ALTER TABLE ai_decision
    ADD COLUMN input_version BIGINT,
    ADD COLUMN request_id VARCHAR(64),
    ALTER COLUMN action DROP NOT NULL,
    DROP CONSTRAINT ck_ai_decision_status,
    ADD CONSTRAINT ck_ai_decision_status CHECK (status IN ('SUCCESS', 'FAILED', 'TIMEOUT', 'INVALID_OUTPUT', 'STALE')),
    ADD CONSTRAINT ck_ai_decision_success_action CHECK (status <> 'SUCCESS' OR action IS NOT NULL),
    ADD CONSTRAINT ck_ai_decision_input_version CHECK (input_version >= 0);

-- 같은 요청의 결과가 두 번 오면 한 번만 적용
CREATE INDEX ix_ai_decision_inquiry_request ON ai_decision (inquiry_id, request_id);


-- ---------------------------------------------------------------------
-- 6. 예약 변경 만료·종료
--    expires_at = 사장님 제안 기한 (제안 후 24시간과 제안 방문 2시간 전 중 빠른 시각)
--    close_reason = CLOSED일 때 이유, resolved_by = 끝낸 쪽 (SYSTEM = 만료·자동 종료)
-- ---------------------------------------------------------------------
ALTER TABLE reservation_change
    ADD COLUMN expires_at TIMESTAMPTZ,
    ADD COLUMN close_reason VARCHAR(30),
    ADD COLUMN resolved_by VARCHAR(20),
    DROP CONSTRAINT ck_reservation_change_status,
    DROP CONSTRAINT ck_reservation_change_type;

-- V1의 취소 요청(CANCEL): 취소는 이제 변경 요청 없이 즉시 처리 → 변경 요청으로는 종료 상태로만 남김
UPDATE reservation_change c
SET change_type  = 'CHANGE',
    status       = 'CLOSED',
    close_reason = CASE WHEN r.status = 'CANCELED' THEN 'RESERVATION_CANCELED' ELSE 'OWNER_CLOSED' END,
    resolved_by  = 'SYSTEM',
    resolved_at  = COALESCE(c.resolved_at, CURRENT_TIMESTAMP),
    request_note = LEFT('[V1 취소 요청] ' || COALESCE(c.request_note, ''), 255)
FROM reservation r
WHERE r.id = c.reservation_id
  AND c.change_type = 'CANCEL';

-- V1의 진행 중 제안: 제안 시각을 모르므로 지금부터 기한을 다시 셈, 이미 지났으면 만료
UPDATE reservation_change
SET expires_at = LEAST(CURRENT_TIMESTAMP + INTERVAL '24 hours', proposed_start_at - INTERVAL '2 hours')
WHERE status = 'PROPOSED';

UPDATE reservation_change
SET status      = 'EXPIRED',
    resolved_by = 'SYSTEM',
    resolved_at = CURRENT_TIMESTAMP
WHERE status = 'PROPOSED'
  AND expires_at <= CURRENT_TIMESTAMP;

ALTER TABLE reservation_change
    ADD CONSTRAINT ck_reservation_change_status CHECK (
        status IN ('REQUESTED', 'PROPOSED', 'ACCEPTED', 'REJECTED', 'APPLIED', 'FAILED', 'EXPIRED', 'CLOSED')),
    ADD CONSTRAINT ck_reservation_change_type CHECK (change_type = 'CHANGE'),
    ADD CONSTRAINT ck_reservation_change_close_reason CHECK (close_reason IN ('RESERVATION_CANCELED', 'OWNER_CLOSED')),
    ADD CONSTRAINT ck_reservation_change_closed CHECK (status <> 'CLOSED' OR close_reason IS NOT NULL),
    ADD CONSTRAINT ck_reservation_change_resolved_by CHECK (resolved_by IN ('CUSTOMER', 'OWNER', 'SYSTEM'));


-- ---------------------------------------------------------------------
-- 7. 알림
--    SKIPPED = 재시도 직전에 보니 보낼 필요가 없어짐 (취소된 예약의 확정 알림 등)
--    V1 사건 종류(CHANGE·CANCEL 등)는 기존 행 때문에 그대로 둠
-- ---------------------------------------------------------------------
ALTER TABLE notification
    DROP CONSTRAINT ck_notification_send_status,
    ADD CONSTRAINT ck_notification_send_status CHECK (send_status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    DROP CONSTRAINT ck_notification_event_type,
    ADD CONSTRAINT ck_notification_event_type CHECK (event_type IN (
        'NEW_RESERVATION', 'NEEDS_CHECK', 'CHANGE', 'CANCEL', 'RESULT',
        'RESERVATION_CONFIRMED', 'CHANGE_PROPOSED', 'CHANGE_APPLIED', 'RESERVATION_CANCELED'));


-- ---------------------------------------------------------------------
-- 8. 인증 대상·요청 IP
--    같은 번호·목적이라도 대상(문의·업체)이 다르면 그 인증을 쓰지 않음
--    request_ip = 번호·IP별 누적 발송 제한 기준 (최근 1시간 IP당 30회)
-- ---------------------------------------------------------------------
ALTER TABLE phone_verification
    ADD COLUMN target_inquiry_id BIGINT,
    ADD COLUMN target_owner_id BIGINT,
    ADD COLUMN request_ip VARCHAR(45),
    ADD CONSTRAINT fk_phone_verification_inquiry FOREIGN KEY (target_inquiry_id) REFERENCES inquiry (id),
    ADD CONSTRAINT fk_phone_verification_owner FOREIGN KEY (target_owner_id) REFERENCES owner (id);

CREATE INDEX ix_phone_verification_ip ON phone_verification (request_ip, created_at);


-- ---------------------------------------------------------------------
-- 9. 접수 항목의 근거 메시지 (같은 문의의 메시지만)
-- ---------------------------------------------------------------------
ALTER TABLE inquiry_field
    ADD COLUMN message_id BIGINT,
    ADD CONSTRAINT fk_inquiry_field_message_same_inquiry FOREIGN KEY (message_id, inquiry_id) REFERENCES message (id, inquiry_id);


-- ---------------------------------------------------------------------
-- 10. 작업별 자동 예약 허용
--     업체 자동 예약(owner.auto_booking_enabled)과 이 값이 모두 켜져야 자동 예약
--     제공하지 않는 작업(is_active = false)은 허용할 수 없음
--     V1에서 이미 자동 예약을 켠 업체는 제공 중인 작업을 허용으로 옮겨 기존 설정을 유지
-- ---------------------------------------------------------------------
ALTER TABLE owner_work_type
    ADD COLUMN auto_booking_allowed BOOLEAN NOT NULL DEFAULT false;

UPDATE owner_work_type w
SET auto_booking_allowed = true
FROM owner o
WHERE o.id = w.owner_id
  AND o.auto_booking_enabled
  AND w.is_active;

ALTER TABLE owner_work_type
    ADD CONSTRAINT ck_owner_work_type_auto_booking CHECK (is_active OR NOT auto_booking_allowed);
